import Script from "next/script";
import { GTM_ID } from "@/lib/site";

/**
 * Contenedor de Google Tag Manager.
 *
 * `afterInteractive` carga el script una vez la página es interactiva: no
 * bloquea el render inicial y sigue midiendo la visita.
 *
 * El `<noscript>` va aparte, al inicio del <body> (ver GTMNoScript), porque
 * es el fallback para navegadores sin JavaScript.
 */
export function GoogleTagManager() {
  if (!GTM_ID) return null;
  return (
    <Script id="gtm-init" strategy="afterInteractive">
      {`(function(w,d,s,l,i){w[l]=w[l]||[];w[l].push({'gtm.start':
new Date().getTime(),event:'gtm.js'});var f=d.getElementsByTagName(s)[0],
j=d.createElement(s),dl=l!='dataLayer'?'&l='+l:'';j.async=true;j.src=
'https://www.googletagmanager.com/gtm.js?id='+i+dl;f.parentNode.insertBefore(j,f);
})(window,document,'script','dataLayer','${GTM_ID}');`}
    </Script>
  );
}

export function GTMNoScript() {
  if (!GTM_ID) return null;
  return (
    <noscript>
      <iframe
        src={`https://www.googletagmanager.com/ns.html?id=${GTM_ID}`}
        height="0"
        width="0"
        style={{ display: "none", visibility: "hidden" }}
        title="Google Tag Manager"
      />
    </noscript>
  );
}
